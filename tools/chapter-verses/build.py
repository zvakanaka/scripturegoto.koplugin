#!/usr/bin/env python3
"""Regenerates scripturegoto.koplugin/chapter_verses.lua: every book's
per-chapter verse counts, in canonical order, from the same
bcbooks/scriptures-json flat files the plugin downloads for preview and
full-text search. Bundled with the plugin (it's small) so the Gospel
Library-style "ne37" search shortcut can tell 1 Nephi 3:7 apart from an
impossible 1 Nephi 37 without downloading anything first.

Usage: tools/chapter-verses/build.py [dir-with-flat-json-files]
(downloads the files itself when no directory is given)
"""
import json
import os
import sys
import urllib.request

BASE_URL = "https://raw.githubusercontent.com/bcbooks/scriptures-json/master/flat/"

# (plugin volume key, flat file) in canonical order
VOLUMES = [
    ("ot", "old-testament-flat.json"),
    ("nt", "new-testament-flat.json"),
    ("bofm", "book-of-mormon-flat.json"),
    ("dc-testament", "doctrine-and-covenants-flat.json"),
    ("pgp", "pearl-of-great-price-flat.json"),
]

# Dataset book name -> book_data.lua canonical name, where they differ
# (the reverse of scripture_data.lua's book_name_overrides).
CANONICAL = {
    "Solomon's Song": "Song of Solomon",
    "D&C": "Doctrine and Covenants",
    "Joseph Smith—Matthew": "Joseph Smith-Matthew",
    "Joseph Smith—History": "Joseph Smith-History",
}


def load(src_dir, name):
    if src_dir:
        with open(os.path.join(src_dir, name), encoding="utf-8") as f:
            return json.load(f)
    with urllib.request.urlopen(BASE_URL + name) as r:
        return json.load(r)


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    src_dir = sys.argv[1] if len(sys.argv) > 1 else None
    out = [
        "-- GENERATED by tools/chapter-verses/build.py - do not edit by hand.",
        "-- Per-chapter verse counts for every book, in canonical order, from",
        "-- https://github.com/bcbooks/scriptures-json (D&C sections count as",
        "-- chapters). Official Declarations aren't in that dataset, so aren't here.",
        "return {",
    ]
    for volume, filename in VOLUMES:
        books = {}
        order = []
        for v in load(src_dir, filename)["verses"]:
            book, cv = v["reference"].rsplit(" ", 1)
            chapter, verse = (int(x) for x in cv.split(":"))
            book = CANONICAL.get(book, book)
            if book not in books:
                books[book] = {}
                order.append(book)
            books[book][chapter] = max(books[book].get(chapter, 0), verse)
        for book in order:
            counts = [books[book][c] for c in sorted(books[book])]
            out.append("    { volume = %s, book = %s, verses = { %s } },"
                       % (lua_str(volume), lua_str(book), ", ".join(map(str, counts))))
    out.append("}")
    dest = os.path.join(os.path.dirname(__file__), "..", "..",
                        "scripturegoto.koplugin", "chapter_verses.lua")
    with open(dest, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print("wrote", os.path.normpath(dest))


if __name__ == "__main__":
    main()
